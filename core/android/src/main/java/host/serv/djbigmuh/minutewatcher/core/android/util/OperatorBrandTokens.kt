    /**
     * Merges multiple token maps into a single map, verifying global uniqueness of keys.
     *
     * @param maps Partial token maps to merge in sequence.
     * @return A merged map preserving the deterministic iteration order of entries.
     * @throws IllegalStateException if any token key appears in more than one partial map.
     */
    internal fun mergeTokenMaps(vararg maps: Map<String, String>): Map<String, String> {
        val result = LinkedHashMap<String, String>()
        for (map in maps) {
            for ((key, value) in map) {
                val previous = result.put(key, value)
                if (previous != null) {
                    throw IllegalStateException(
                        "Duplicate operator brand token key '$key' mapped to '$previous' and '$value'",
                    )
                }
            }
        }
        return result
    }

