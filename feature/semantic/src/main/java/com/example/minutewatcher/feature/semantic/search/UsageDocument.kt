package com.example.minutewatcher.feature.semantic.search

import androidx.appsearch.annotation.Document
import androidx.appsearch.annotation.Document.Id
import androidx.appsearch.annotation.Document.LongProperty
import androidx.appsearch.annotation.Document.Namespace
import androidx.appsearch.annotation.Document.Score
import androidx.appsearch.annotation.Document.StringProperty
import androidx.appsearch.app.AppSearchSchema
import com.example.minutewatcher.core.model.GlobalSnapshot
import com.example.minutewatcher.core.model.SemanticEntity
import com.example.minutewatcher.core.model.util.ColorProvider

/**
 * DTO for AppSearch usage data indexing.
 *
 * **Dependency on annotation processor:** converter class
 * `$$__AppSearch__UsageDocument` is generated by `appsearch-compiler` (KSP).
 * Without KSP working, converter will not be generated, and AppSearch
 * will throw [androidx.appsearch.exceptions.AppSearchException] with RESULT_INTERNAL_ERROR when attempting
 * indexing. This is a build issue, not runtime.
 *
 * **ProGuard/R8:** keep rules for `$$__AppSearch__*` are located
 * in `feature/semantic/consumer-rules.pro`. Removing these rules will cause
 * converter removal from release builds.
 *
 * **Strict API compliance:** field structure and annotations conform
 * to contract of [Document].
 *
 * **WARNING:** changing the set of fields requires:
 * 1. Schema version increment in [SemanticSearchManager].
 * 2. Migration handling via forceOverride in ensureSession().
 * Failure to comply leads to RESULT_INVALID_SCHEMA at launch.
 *
 * **Custom ROM deviation:** if custom firmware
 * does not support AppSearch — this is a custom firmware issue.
 * Strategy: TrackingStatus.ErrorType.NOT_SUPPORTED.
 */
@Document
class UsageDocument {
    @Namespace
    var namespace: String = ""

    @Id
    var id: String = ""

    @Score
    var score: Int = 0

    @StringProperty(indexingType = AppSearchSchema.StringPropertyConfig.INDEXING_TYPE_PREFIXES)
    var operatorName: String = ""

    @StringProperty
    var packageType: String = ""

    @LongProperty
    var remainingValue: Long = 0

    @StringProperty
    var unit: String = ""

    @LongProperty
    var usedValue: Long = 0

    @LongProperty
    var limitValue: Long = 0

    @LongProperty
    var remainingPercent: Long = 0

    @LongProperty
    var periodEnd: Long = 0

    @LongProperty
    var slot: Long = 0

    @StringProperty
    var status: String = ""

    // @Suppress("unused") is required for AppSearch reflection-based instantiation.

    /**
     * Required no-arg constructor for AppSearch.
     *
     * **Strict API compliance:** [Document] requires
     * a public no-arg constructor for reflective deserialization.
     * Called via [androidx.appsearch.app.GenericDocument.toDocumentClass].
     * Removal leads to [androidx.appsearch.exceptions.AppSearchException]
     * (RESULT_INTERNAL_ERROR) at runtime.
     *
     * **Custom ROM deviation:** if custom firmware does not provide
     * correct reflection for AppSearch — this is a custom firmware issue.
     */
    @Suppress("unused")
    constructor()

    // UsageDocument is a DTO for AppSearch, flat schema requires all fields in one class.
    // @Suppress("LongParameterList") is required because AppSearch requires a flat DTO schema.
    @Suppress("LongParameterList")
    constructor(
        namespace: String,
        id: String,
        score: Int,
        operatorName: String,
        packageType: String,
        remainingValue: Long,
        unit: String,
        usedValue: Long,
        limitValue: Long,
        remainingPercent: Long,
        periodEnd: Long,
        slot: Long,
        status: String,
    ) {
        this.namespace = namespace
        this.id = id
        this.score = score
        this.operatorName = operatorName
        this.packageType = packageType
        this.remainingValue = remainingValue
        this.unit = unit
        this.usedValue = usedValue
        this.limitValue = limitValue
        this.remainingPercent = remainingPercent
        this.periodEnd = periodEnd
        this.slot = slot
        this.status = status
    }

    companion object {
        private const val PERCENT_MAX = 100

        fun fromSemanticEntity(entity: SemanticEntity): UsageDocument {
            val percent = if (entity.limit > 0) ((entity.remaining * PERCENT_MAX) / entity.limit) else 0L
            val usageStatus = ColorProvider.getUsageStatus(entity.remaining.toFloat(), entity.limit.toFloat()).name

            return UsageDocument(
                namespace = AppSearchConstants.NAMESPACE,
                id = entity.id,
                score = 0,
                operatorName = entity.operatorName,
                packageType = entity.packageType.name,
                remainingValue = entity.remaining,
                unit = entity.unit.name,
                usedValue = entity.used,
                limitValue = entity.limit,
                remainingPercent = percent,
                periodEnd = entity.periodEnd,
                slot = entity.simSlot.toLong(),
                status = usageStatus,
            )
        }

        fun fromGlobalSnapshot(snapshot: GlobalSnapshot): List<UsageDocument> {
            val documents = mutableListOf<UsageDocument>()
            for (sim in snapshot.simSnapshots) {
                for (entity in sim.entities.values) {
                    documents.add(fromSemanticEntity(entity))
                }
            }
            return documents
        }
    }
}
